"""Render E1 cells as markdown tables (pure formatting of results/e1_results_long.csv)."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

OUT = Path(__file__).resolve().parents[1]
d = pd.read_csv(OUT / "results" / "e1_results_long.csv")


def f(x, nd=3):
    return "n/a" if pd.isna(x) else f"{x:.{nd}f}"


lines = ["# E1 tables (generated by code/e1_tables.py from results/e1_results_long.csv)", ""]
lines += ["Cell format: budget-violation probability; median realised FPR [5th, 95th percentile]; "
          "median recall [5th, 95th]. For P2 the share of draws with no certifiable cutoff is given as nc; "
          "statistics for P2 are over certified draws only. Evaluation is on the unlabelled remainder.", ""]
for alpha in sorted(d.alpha.unique()):
    lines += [f"## alpha = {alpha}", ""]
    for target in ["trec6", "trec5", "spaphish", "ceas08"]:
        sub = d[(d.alpha == alpha) & (d.target == target)]
        lines += [f"### {target}", "", "| model | route | policy | k | viol. prob | FPR median [p5, p95] | recall median [p5, p95] | nc |",
                  "|:-|:-|:-|-:|-:|:-|:-|-:|"]
        for (m, r), g in sub.groupby(["model", "route"], sort=False):
            for pol in ["P0", "P1", "P2", "P3", "P4"]:
                gp = g[g.policy == pol].sort_values("k")
                for _, row in gp.iterrows():
                    lines.append(f"| {m} | {r} | {pol} | {int(row.k)} | {f(row.budget_violation_prob)} | "
                                 f"{f(row.fpr_median, 4)} [{f(row.fpr_p05, 4)}, {f(row.fpr_p95, 4)}] | "
                                 f"{f(row.recall_median)} [{f(row.recall_p05)}, {f(row.recall_p95)}] | {f(row.no_cutoff_share)} |")
        lines.append("")
(OUT / "results" / "e1_tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(lines))

# compact pivots: one row per target x model x route x policy, columns k
piv = []
for alpha in sorted(d.alpha.unique()):
    x = d[d.alpha == alpha]
    for val, label in [("budget_violation_prob", "budget-violation probability"), ("recall_median", "median recall on the remainder")]:
        ks = sorted(x.k.unique())
        piv += [f"### alpha = {alpha}: {label}", "", "| target | model | route | policy | " + " | ".join(f"k={k}" for k in ks) + " |",
                "|:-|:-|:-|:-|" + "-:|" * len(ks)]
        for (t, m, r, p), g in x.groupby(["target", "model", "route", "policy"], sort=False):
            vals = {int(row.k): row[val] for _, row in g.iterrows()}
            cells = []
            for k in ks:
                if k not in vals:
                    cells.append("excl.")
                elif pd.isna(vals[k]):
                    cells.append("nc")
                else:
                    cells.append(f"{vals[k]:.3f}")
            piv.append(f"| {t} | {m} | {r} | {p} | " + " | ".join(cells) + " |")
        piv.append("")
(OUT / "results" / "e1_pivots.md").write_text("\n".join(piv) + "\n", encoding="utf-8")
